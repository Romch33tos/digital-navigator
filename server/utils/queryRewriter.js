export async function rewriteQuery(llm, question, history) {
  if (!history || history.length === 0) {
    return question;
  }

  const historyText = history
    .map(msg => `${msg.role === 'user' ? 'Студент' : 'Ассистент'}: ${msg.text}`)
    .join('\n');

  const rewritePrompt = `Ты — поисковый ассистент. Твоя задача — переформулировать последний вопрос студента, используя контекст диалога.

История диалога:
${historyText}

Последнее сообщение пользователя: "${question}"

ПРАВИЛА:
1. Если в сообщении есть эмоции, присказки или нецензурная лексика — полностью игнорируй их.
2. НЕ ВЫДУМЫВАЙ имена собственные, названия или сущности, которых нет в тексте.
3. Объедини смысл последнего сообщения с контекстом предыдущих, чтобы получился один понятный поисковый запрос.
4. Верни ТОЛЬКО текст нового запроса, без кавычек и пояснений.

Пример:
Последнее сообщение: "ой блин потерял пропуск че делать?"
Правильный ответ: "Что делать, если потерял пропуск?"
Неправильный ответ: "Что делать, если блин потерял пропуск?"`;

  try {
    const response = await llm.invoke([
      { role: 'system', content: 'Ты помогаешь формулировать поисковые запросы. Отвечай только текстом запроса.' },
      { role: 'user', content: rewritePrompt }
    ]);
    return response.content.trim();
  } catch (error) {
    console.error('[LLM] Ошибка при переписывании запроса:', error);
    return question;
  }
}
